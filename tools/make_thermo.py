#!/usr/bin/env python3
"""
Write constant/fluid/thermophysicalProperties for the dielectric ester.

chtMultiRegionFoam builds a rhoReactionThermo; its only temperature-dependent
liquid option for a pureMixture is polynomial / hPolynomial / icoPolynomial.
rho, Cp and kappa are linear in T so the polynomials are exact.  mu is Arrhenius
and needs a genuine fit -- and a polynomial extrapolates catastrophically, so
the fit is deliberately taken over 295-450 K (wider than the run will reach) and
then VERIFIED to stay positive and monotonically decreasing past 600 K.  A
negative mu anywhere in the domain would blow the solver up instantly.
"""
import sys, numpy as np
sys.path.insert(0, "tools")
import fluid_props as fp

MU_FIT_LO, MU_FIT_HI, MU_DEG = 295.0, 450.0, 6
WORK_LO, WORK_HI = 300.0, 400.0            # bath -> hottest expected can surface

def fit(fn, lo, hi, deg, relative=True):
    T = np.arange(lo, hi + 1e-9, 2.5)
    y = np.array([fn(t) for t in T])
    c = np.polyfit(T, y, deg, w=(1.0 / y if relative else None))
    return c[::-1]                          # OpenFOAM order: a0 + a1*T + a2*T^2 ...

def check(c, fn, label):
    Tw = np.arange(WORK_LO, WORK_HI + 0.1, 1.0)
    ex = np.array([fn(t) for t in Tw])
    err = np.max(np.abs(np.polyval(c[::-1], Tw) - ex) / ex) * 100
    Tz = np.arange(MU_FIT_LO, 620.0, 0.5)
    v = np.polyval(c[::-1], Tz)
    assert v.min() > 0, "{} goes non-positive at T = {:.0f} K".format(label, Tz[v <= 0][0])
    print("  {:<6s} max err {:.3f} % over {:.0f}-{:.0f} K; positive and well-behaved to 620 K"
          .format(label, err, WORK_LO, WORK_HI))
    return c

def coeffs(c):
    c = list(c) + [0.0] * (8 - len(c))
    return "( " + " ".join(("{: .10e}".format(v) if v else "0") for v in c) + " )"

print("Fitting ester property polynomials:")
c_rho = check(fit(fp.rho, 280, 450, 1, False), fp.rho, "rho")
c_cp  = check(fit(fp.cp,  280, 450, 1, False), fp.cp,  "Cp")
c_kap = check(fit(fp.kap, 280, 450, 1, False), fp.kap, "kappa")
c_mu  = check(fit(fp.mu,  MU_FIT_LO, MU_FIT_HI, MU_DEG), fp.mu, "mu")

TXT = """/*--------------------------------*- C++ -*----------------------------------*\\
| Dielectric coolant: model liquid of the synthetic-ester type (see the       |
| article).  Generated by tools/make_thermo.py -- DO NOT EDIT BY HAND.        |
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       dictionary;
    location    "constant/fluid";
    object      thermophysicalProperties;
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

// All four properties vary with temperature.  That matters most for viscosity:
// the ester thins by roughly 8x between the 35 C bath and the ~110 C can
// surface, and that is what sets the strength of the buoyant plume.  A constant
// mu evaluated at bath temperature would badly under-predict the cooling.
//
//   T [C]      25      35      55      75      95     115
//   nu [cSt]  42.9    30.5    17.4    10.6     6.9     4.7
//   Pr       ~520    ~380    ~230    ~130     ~85     ~57
//
// rho is a genuine rho(T), not a Boussinesq linearisation, so buoyancy stays
// correct across the ~75 K span the plume actually sees.
// Fits: rho / Cp / kappa are linear and exact; mu is an Arrhenius fit
// nu = {A:.6e} * exp({B:.1f}/T) reduced to a degree-{deg:d} polynomial over
// {lo:.0f}-{hi:.0f} K, max error {muerr:.2f} % over 300-400 K.

thermoType
{{
    type            heRhoThermo;
    mixture         pureMixture;
    transport       polynomial;
    thermo          hPolynomial;
    equationOfState icoPolynomial;
    specie          specie;
    energy          sensibleEnthalpy;
}}

mixture
{{
    specie
    {{
        molWeight       340;        // representative ester MW; the polynomial
    }}                              // coefficients below are in mass units

    equationOfState
    {{
        rhoCoeffs<8>    {rho};
    }}

    thermodynamics
    {{
        Hf              0;
        Sf              0;
        CpCoeffs<8>     {cp};
    }}

    transport
    {{
        muCoeffs<8>     {mu};
        kappaCoeffs<8>  {kappa};
    }}
}}

// ************************************************************************* //
"""

Tw = np.arange(WORK_LO, WORK_HI + 0.1, 1.0)
muerr = np.max(np.abs(np.polyval(c_mu[::-1], Tw) - [fp.mu(t) for t in Tw]) /
               [fp.mu(t) for t in Tw]) * 100

out = sys.argv[1] if len(sys.argv) > 1 else "thermophysicalProperties"
open(out, "w").write(TXT.format(
    A=fp.A, B=fp.B, deg=MU_DEG, lo=MU_FIT_LO, hi=MU_FIT_HI, muerr=muerr,
    rho=coeffs(c_rho), cp=coeffs(c_cp), mu=coeffs(c_mu), kappa=coeffs(c_kap)))
print("\nwrote {}".format(out))
