#!/usr/bin/env python3
"""smoke_report.py -- build RUNLOG.md from smoke/*/result.json (run after run_smoke.sh)."""
import glob
import json
import math
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SM = os.path.join(HERE, 'smoke')


def load(name):
    f = os.path.join(SM, name, 'result.json')
    return json.load(open(f)) if os.path.exists(f) else None


def e(x, d=3):
    return 'n/a' if x is None else f'{x:.{d}e}'


def f(x, d=6):
    return 'n/a' if x is None else f'{x:.{d}f}'


def order(a, b, ratio=2.0):
    return math.log(abs(a) / abs(b)) / math.log(ratio) if a and b else float('nan')


out = []
w = out.append
ver = subprocess.run(['bash', '-c', 'openfoam2606 -c "foamVersion" 2>/dev/null | tail -1'], capture_output=True, text=True).stdout.strip()
w('# Run log of the smoke instances\n')
w(f'Generated by `smoke_report.py` from `smoke/*/result.json`. Serial, one core, '
  f'niceness 10. OpenFOAM: {ver or "v2606 (openfoam2606)"}. Solver: `chtMultiRegionFoam` with two solid regions '
  '(`regionProperties`: `fluid ()`, `solid (iso aniso)`); the single-region references use `solidFoam`.\n')
w('All numbers below are **measured in this job** unless a column is headed "predicted" or "exact". Heat rates are '
  'W per metre depth, energies J per metre depth. The chronological log with wall times is `smoke/run_smoke.log`.\n')

# ----------------------------------------------------------------------------- P1
w('\n## S1. Oblique planar interface, patch test (problem 1)\n')
w('Two 10 mm squares, K = R(theta) diag(28, 0.8, 0.8) R^T in `aniso`, k = 1 in `iso`, exact field '
  'T = 320 + A x + B y (aniso), 320 + A_i x + B y (iso), A = 1000, B = 500 K/m, exact values on all outer '
  'boundaries, pseudo-time march from a uniform field. Primary instance: `p1_dir_t30_n16`.\n')
w('| case | coupling | theta | cells/side | Linf error vs exact [K] | into iso [W/m] | out of aniso [W/m] | exact rate [W/m] | '
  'created at interface [W/m] | predicted K_nt B H [W/m] | stock `wallHeatFlux`, aniso [W/m] | change since previous write [K] |')
w('|---|---|---|---|---|---|---|---|---|---|---|---|')
for n in ('p1_dir_t30_n8', 'p1_dir_t30_n16', 'p1_dir_t30_n32', 'p1_sca_t30_n16', 'p1_con_t30_n16', 'p1_dir_t0_n16',
          'p1_dir_t30_n16_rot'):
    r = load(n)
    if not r:
        w(f'| {n} | not run | | | | | | | | | | |')
        continue
    P, i, x = r['params'], r['interface'], r['exact']
    w(f"| {n} | {P['coupling']} | {P['theta']:g} | {P['nxa']} | {e(r['error']['exact']['all']['Linf'])} | "
      f"{f(i['into_iso'], 4)} | {f(-i['into_aniso'], 4)} | {f(x['rate_plus_xi'], 4)} | {e(i['imbalance'])} | "
      f"{f(x['predicted_creation'], 4)} | {f(-i.get('stock_wallHeatFlux_aniso', float('nan')), 4)} | "
      f"{e(r.get('steady_change_since_previous_write'))} |")
w('\nSign convention: "into iso" and "out of aniso" are both the heat rate crossing the interface in the direction '
  'aniso -> iso (negative here because the exact flux runs from iso to aniso); "created" = into iso minus out of aniso.\n')
rr = [load(n) for n in ('p1_dir_t30_n8', 'p1_dir_t30_n16', 'p1_dir_t30_n32')]
if all(rr):
    v = [r['error']['exact']['all']['Linf'] for r in rr]
    w(f'Stock directional option under refinement (8, 16, 32 cells per side): Linf = {v[0]:.4f}, {v[1]:.4f}, {v[2]:.4f} K: '
      'no convergence. Per-region steady audits (sum over all patches of a region, tensor-correct on `aniso`) close to '
      + ', '.join(e(max(abs(r['region_audit']['aniso']), abs(r['region_audit']['iso'])), 1) for r in rr) + ' W/m, which shows '
      'that the flux evaluation in `post.py` is the solver\'s own operator.\n')
w('Sheared strip (eta-walls carry the exact gradient B; closed-form scheme solution, section 3.1 of DESIGN.md):\n')
w('| case | coupling | Linf vs exact [K] | Linf vs closed-form scheme solution [K] | wall temperature error, predicted [K] | '
  'measured mean wall error [K] | created [W/m] | predicted [W/m] |')
w('|---|---|---|---|---|---|---|---|')
for n in ('p1_shear_dir_t30', 'p1_shear_sca_t30', 'p1_shear_con_t30'):
    r = load(n)
    if not r:
        w(f'| {n} | not run | | | | | | |')
        continue
    P, i, x = r['params'], r['interface'], r['exact']
    meas = i['Tw_aniso'] - P['B'] * P['H'] / 2 - x['Tw']
    w(f"| {n} | {P['coupling']} | {e(r['error']['exact']['all']['Linf'])} | {e(r['error']['scheme']['all']['Linf'])} | "
      f"{f(x['scheme_wall_error_sheared'], 6)} | {f(meas, 6)} | {e(i['imbalance'])} | {f(x['predicted_creation'], 4)} |")
w('\nSingle-region reference (`solidFoam`, `pureZoneMixture`, same mesh, 8 correctors per step):\n')
w('| case | theta | cells/side | Linf vs exact [K] | L2 [K] |')
w('|---|---|---|---|---|')
mv = []
for n in ('p1_dir_t30_n8', 'p1_dir_t30_n16', 'p1_dir_t30_n32', 'p1_dir_t0_n16'):
    r = load(n + '_mono')
    if r:
        w(f"| {n}_mono | {n.split('_t')[1].split('_')[0]} | {n.split('_n')[1]} | {e(r['Linf'])} | {e(r['L2'])} |")
        if 't30' in n:
            mv.append(r['Linf'])
if len(mv) == 3:
    w(f'\nObserved order of the single-region solver on the oblique interface: {order(mv[0], mv[1]):.2f}, {order(mv[1], mv[2]):.2f} '
      '(first order; it does not pass the patch test but it converges, unlike the partitioned stock coupling).\n')

# ----------------------------------------------------------------------------- P2
w('\n## S2. Concentric annulus (problem 2)\n')
w('r1 = 4, r2 = 9, r3 = 15 mm, T(r1) = 350 K, T(r3) = 300 K, outer k = 0.15. Variant A: 90 degree sector, '
  '(k_r, k_theta, k_z) = (0.8, 0.8, 28) in a cylindrical coordinate system. Variant B: full ring, (0.8, 28, 28). '
  'Variant C: variant B on a 90 degree sector with zero-gradient side planes. Q\' is the heat rate per radian and per '
  'metre depth; exact Q\' = '
  + (f(load('p2_dir_A_L1')['exact']['Qp'], 6) if load('p2_dir_A_L1') else 'n/a') + ' W/m/rad. Primary instance: `p2_dir_A_L1`.\n')
w('| case | coupling | cells (aniso+iso) | L2 vs exact [K] | Linf vs exact [K] | Linf vs scheme [K] | Q\' inner wall | Q\' out of aniso | '
  'Q\' into iso | Q\' outer wall | scheme Q\' in / out (predicted) | interface imbalance [W/m] | change since previous write [K] |')
w('|---|---|---|---|---|---|---|---|---|---|---|---|---|')
for n in ('p2_dir_A_L1', 'p2_dir_A_L2', 'p2_dir_A_L3', 'p2_sca_A_L1', 'p2_sca_A_L2', 'p2_dir_B_ring', 'p2_dir_C_trap',
          'p2_dir_C_trap_nth64', 'p2_sca_C_trap'):
    r = load(n)
    if not r:
        lg_ = os.path.join(SM, n, 'log.chtMultiRegionFoam')
        why = 'not run'
        if os.path.exists(lg_):
            t_ = open(lg_).read()
            if 'FOAM FATAL ERROR' in t_:
                why = ('solver aborted after ' + str(t_.count(chr(10) + 'Time = ')) + ' steps: '
                       + t_.split('FOAM FATAL ERROR')[-1].strip().splitlines()[1].strip())
        w(f'| {n} | {why} | | | | | | | | | | | |')
        continue
    P, i, x, m = r['params'], r['interface'], r['exact'], r['measured_Qp']
    w(f"| {n} | {P['coupling']} | {r['cells']['aniso']}+{r['cells']['iso']} | {e(r['error']['exact']['all']['L2'])} | "
      f"{e(r['error']['exact']['all']['Linf'])} | {e(r['error']['scheme']['all']['Linf'])} | {f(m['inner_wall'], 5)} | "
      f"{f(m['interface_out_of_aniso'], 5)} | {f(m['interface_into_iso'], 5)} | {f(m['outer_wall'], 5)} | "
      f"{f(x['scheme_Qp_in'], 5)} / {f(x['scheme_Qp_out'], 5)} | {e(i['imbalance'])} | "
      f"{e(r.get('steady_change_since_previous_write'))} |")
rr = [load(n) for n in ('p2_dir_A_L1', 'p2_dir_A_L2', 'p2_dir_A_L3')]
if all(rr):
    for key in ('L2', 'Linf'):
        v = [r['error']['exact']['all'][key] for r in rr]
        w(f'\nObserved order, directional, variant A, {key}: {order(v[0], v[1]):.2f}, {order(v[1], v[2]):.2f} '
          f'(errors {v[0]:.3e}, {v[1]:.3e}, {v[2]:.3e} K).')
    q = [abs(r['measured_Qp']['interface_into_iso'] - r['exact']['Qp']) for r in rr]
    w(f'\nObserved order of the interface heat rate: {order(q[0], q[1]):.2f}, {order(q[1], q[2]):.2f} '
      f'(errors {q[0]:.3e}, {q[1]:.3e}, {q[2]:.3e} W/m/rad).\n')
rr = [load(n) for n in ('p2_sca_A_L1', 'p2_sca_A_L2')]
if all(rr):
    v = [r['error']['exact']['all']['Linf'] for r in rr]
    s = [r['error']['scheme']['all']['Linf'] for r in rr]
    g = [r['measured_Qp']['interface_into_iso'] / r['measured_Qp']['interface_out_of_aniso'] for r in rr]
    w(f'Scalar option, variant A, two meshes: error against the exact solution {v[0]:.3f}, {v[1]:.3f} K (does not fall); '
      f'error against the scheme solution {s[0]:.3e}, {s[1]:.3e} K (order {order(s[0], s[1]):.2f}); measured '
      f"Q'(into iso)/Q'(out of aniso) = {g[0]:.6f}, {g[1]:.6f}; predicted |K|/k_r = "
      f"{rr[0]['exact']['kc'] / rr[0]['exact']['knn']:.6f}.\n")

# ----------------------------------------------------------------------------- P3
w('\n## S3. Transient two-layer slab (problem 3)\n')
w('aniso 4 mm (K rotated by 60 degrees, so n.K.n = 7.6), iso 6 mm (k = 0.15); rho c_p = 2.0e6 and 1.5e6 J/m3/K; both ends '
  'adiabatic; initial temperatures 350 K and 300 K; 32 + 48 cells; end time 40 s. Primary instance: `p3_dir_dt02`. '
  'The columns separate the error sources as described in DESIGN.md section 5.4.\n')
w('| case | coupling | dt [s] | passes | order | solver minus emulator [K] | staggering [K] | implicit Euler [K] | space [K] | '
  'conservation defect [K] | energy ratio received/released | emulator ratio | continuum prediction | drift dE_a+dE_i [J/m] |')
w('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
for n in ('p3_dir_dt04', 'p3_dir_dt02', 'p3_dir_dt01', 'p3_dir_dt02_o3', 'p3_dir_dt02_rev', 'p3_sca_dt02', 'p3_sca_dt01'):
    r = load(n)
    if not r:
        w(f'| {n} | not run | | | | | | | | | | | | |')
        continue
    P, a = r['params'], r['audit']
    s = a['split_Linf_K']
    w(f"| {n} | {P['coupling']} | {P['dt']:g} | {P['nouter']} | {P['order']} | {e(s['solver_minus_emulator'], 1)} | "
      f"{e(s['staggering__emulator_minus_monolithic'])} | {e(s['euler__monolithic_minus_semidiscrete'])} | "
      f"{e(s.get('space__semidiscrete_minus_series_scheme'))} | "
      f"{e(s.get('conservation_defect__series_scheme_minus_series_exact'))} | {f(a['ratio_received_over_released'], 6)} | "
      f"{f(a['emulator']['ratio'], 6)} | {f(a['predicted_ratio_continuum'], 6)} | {f(a['drift'], 4)} |")
rr = [load(n) for n in ('p3_dir_dt04', 'p3_dir_dt02', 'p3_dir_dt01')]
if all(rr):
    for key, lab in (('staggering__emulator_minus_monolithic', 'staggering error'),
                     ('euler__monolithic_minus_semidiscrete', 'implicit-Euler error')):
        v = [r['audit']['split_Linf_K'][key] for r in rr]
        w(f'\nObserved temporal order of the {lab}: {order(v[0], v[1]):.2f}, {order(v[1], v[2]):.2f}.')
    v = [r['audit']['drift'] for r in rr]
    w(f'\nObserved temporal order of the energy drift: {order(v[0], v[1]):.2f}, {order(v[1], v[2]):.2f}.')
    v = [r['error']['exact']['all']['Linf'] for r in rr]
    w(f'\nObserved temporal order of the total error against the series solution: {order(v[0], v[1]):.2f}, {order(v[1], v[2]):.2f}.\n')
r = load('p3_dir_dt02_mono')
if r:
    import numpy as np
    sys.path.insert(0, HERE)
    import fv1d, gencase, ofio
    mc = os.path.join(SM, 'p3_dir_dt02_mono')
    Pm = json.load(open(os.path.join(mc, 'bench.json')))
    Em = gencase.exact_objects(Pm)
    mm = ofio.Mesh(os.path.join(mc, 'constant', 'polyMesh'))
    Tm_of = ofio.read_field(os.path.join(mc, ofio.time_dirs(mc)[-1][1], 'T'), mm.nCells)[0][np.argsort(mm.C[:, 0])]
    stm = fv1d.Strip1D(Em['knn'], Em['knn'], Em['Ca'], Pm['La'], Pm['nxa'], Pm['ki'], Em['Ci'], Pm['Li'], Pm['nxi'])
    xm = stm.x()
    Tm_ref = stm.monolithic(gencase.initial_T(Pm, Em, xm, 0 * xm), Pm['dt'], Pm['nsteps'])
    w(f"Single-region reference `p3_dir_dt02_mono` (`solidFoam`, 30 correctors per step): Linf vs series {e(r['Linf'])} K, "
      f"energy change {e(r['energy_change_J_per_m'], 1)} J/m of {e(r['energy_initial_J_per_m'], 3)} J/m; "
      f"difference to the monolithic implicit-Euler reference `fv1d.Strip1D.monolithic` on the same mesh and time step: "
      f"{e(float(np.max(np.abs(Tm_of - Tm_ref))), 1)} K.\n")
w('Sheared transient (tangential gradient B = 2000 K/m, fixed end temperatures, theta = 30 degrees):\n')
w('| case | coupling | dt [s] | Linf vs exact series [K] | Linf vs scheme series [K] | solver minus emulator [K] |')
w('|---|---|---|---|---|---|')
for n in ('p3s_dir_dt02', 'p3s_con_dt02', 'p3s_con_dt01'):
    r = load(n)
    if not r:
        w(f'| {n} | not run | | | | |')
        continue
    P, a = r['params'], r['audit']
    w(f"| {n} | {P['coupling']} | {P['dt']:g} | {e(r['error']['exact']['all']['Linf'])} | "
      f"{e(r['error'].get('scheme', {}).get('all', {}).get('Linf'))} | {e(a['split_Linf_K']['solver_minus_emulator'], 1)} |")

# ----------------------------------------------------------------------------- P4
w('\n\n## S4. Aligned two-layer slab, flux-ratio check (problem 4)\n')
w('Same slab as S3 with 16 + 24 cells, dt = 0.05 s, 20 s. "Storage ratio" is -dE_iso/dE_aniso over the whole run, from the '
  'written fields. With one pass per step it contains the staggering term; with four passes that term is below 1e-8. '
  'The emulator column is the same quantity from `fv1d.Strip1D.partitioned`, which implements the hypothesised algebra. '
  'Primary instance: `p4_sca_t90`.\n')
w('| case | coupling | principal k | theta | passes | coupling conductivity k_c | n.K.n | predicted k_c/(n.K.n) | storage ratio (solver) | '
  'storage ratio (emulator) | solver/predicted - 1 | stock `wallHeatFlux` aniso/iso at t_end | written valueFraction minus predicted | Linf vs scheme [K] |')
w('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
from exact import knn_knt
for n in ('p4_sca_t90', 'p4_sca_t90_fine', 'p4_sca_t90_o4', 'p4_sca_t0', 'p4_sca_t0_o4', 'p4_sca_kkk', 'p4_sca_kkk_o4', 'p4_dir_kkk',
          'p4_fun_t90_kc5', 'p4_fun_t90_kc5_o4', 'p4_dir_t90', 'p4_dir_t90_o4'):
    r = load(n)
    if not r:
        w(f'| {n} | not run | | | | | | | | | | | | |')
        continue
    P, a, i = r['params'], r['audit'], r['interface']
    kc = a['predicted_ratio_continuum']
    whf = -i['stock_wallHeatFlux_aniso'] / i['stock_wallHeatFlux_iso'] if 'stock_wallHeatFlux_iso' in i else None
    knn = knn_knt((P['k1'], P['k2'], P['k3']), P['theta'])[0]
    w(f"| {n} | {P['coupling']} | ({P['k1']:g}, {P['k2']:g}, {P['k3']:g}) | {P['theta']:g} | {P['nouter']} | {f(kc * knn, 6)} | {f(knn, 4)} | "
      f"{f(kc, 9)} | {f(a['ratio_received_over_released'], 9)} | {f(a['emulator']['ratio'], 9)} | "
      f"{e(a['ratio_received_over_released'] / kc - 1, 1)} | "
      f"{f(whf, 6)} | {e(i.get('valueFraction_maxdiff'), 1)} | {e(r['error']['scheme']['all']['Linf'])} |")
w('\nA two-sided ratio formed from the two first-cell temperatures of one instant is k_c/(n.K.n) by the algebra of the wall balance '
  'and is therefore not listed as a measurement. Solver-side evidence is the storage ratio above, the written `valueFraction`, '
  'and, in the steady cases S1 and S2, the two heat rates evaluated separately with each region\'s own stencil.\n')

# ----------------------------------------------------------------------------- probes
w('\n\n## X. Probes of the assembled implicit coupling (`useImplicit true`), not part of the four problems\n')
w('Same slab as S4 at theta = 90 degrees with dt = 0.5 s, 100 s. "Monolithic reference" is the implicit-Euler solution of '
  'the coupled system on the same mesh (`fv1d.Strip1D.monolithic`).\n')
w('| case | coupling | c_p aniso / iso | passes | energy ratio | drift [J/m] | Linf vs exact series [K] | solver minus monolithic reference [K] |')
w('|---|---|---|---|---|---|---|---|')
sys.path.insert(0, HERE)
for n in ('x_expl_dir_eqcp', 'x_impl_dir_eqcp', 'x_impl_dir_cp15', 'x_impl_dir_cp15_o10', 'x_impl_sca_eqcp'):
    r = load(n)
    if not r:
        w(f'| {n} | not run or failed | | | | | | |')
        continue
    P, a = r['params'], r['audit']
    s = a['split_Linf_K']
    # solver - monolithic = (solver - emulator) is not available directly; reconstruct from the stored split
    import numpy as np
    import post as _post, fv1d, gencase
    c = _post.Case(os.path.join(SM, n))
    st = fv1d.Strip1D(c.E['knn'], c.E['kc'], c.E['Ca'], P['La'], P['nxa'], P['ki'], c.E['Ci'], P['Li'], P['nxi'])
    x1 = st.x()
    Tm = st.monolithic(gencase.initial_T(P, c.E, x1, 0 * x1), P['dt'], P['nsteps'])
    tn = c.times[-1][1]
    Tof = np.concatenate([c.field(tn, rg, 'T')[0][np.argsort(c.coords(c.mesh[rg].C)[0])] for rg in ('aniso', 'iso')])
    w(f"| {n} | {P['coupling']}{' implicit' if P['implicit'] == 'yes' else ' explicit'} | {P['cpA']:g} / {P['cpI']:g} | {P['nouter']} | "
      f"{f(a['ratio_received_over_released'], 6)} | {e(a['drift'])} | {e(r['error']['exact']['all']['Linf'])} | "
      f"{e(float(np.max(np.abs(Tof - Tm))))} |")

w('\n\n## Chronological log\n\n```')
lg = os.path.join(SM, 'run_smoke.log')
if os.path.exists(lg):
    w(open(lg).read().rstrip())
w('```\n')
open(os.path.join(HERE, 'RUNLOG.md'), 'w').write('\n'.join(out) + '\n')
print('wrote RUNLOG.md,', len(out), 'lines')
